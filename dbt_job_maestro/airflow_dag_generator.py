    def _is_generated_file(self, path: str) -> bool:
        """Return True if a file was produced by maestro (current or legacy)."""
        try:
            with open(path, "r") as f:
                head = f.read(512)
        except OSError:
            return False
        return GENERATED_PHRASE in head
