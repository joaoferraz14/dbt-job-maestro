V3 = read_all("18-af-v3")
if V3:
    print("\n=== 18-af-v3: Airflow 3 targeting ===")
    c18 = cfg_of("18-af-v3")
    check("config requests airflow_version 3", c18.airflow.airflow_version == 3)
    check(
        "v3 uses schedule= not schedule_interval=",
        all("schedule_interval=" not in v for v in V3.values())
        and all(re.search(r"^\s+schedule=", v, re.M) for v in V3.values()),
    )
    check(
        "v3 uses the provider BashOperator import",
        all(
            "from airflow.providers.standard.operators.bash import BashOperator" in v
            for v in V3.values()
        ),
    )
    check(
        "v3 omits sla (removed in Airflow 3.0)",
        not any('"sla"' in v for v in V3.values()),
        f"sla_minutes={c18.airflow.sla_minutes}",
    )

print("\n=== selector names that are not valid Python identifiers ===")
odd = {
    k: v
    for k, v in SIMPLE.items()
    if not re.sub(r"\.py$", "", k).replace("-", "_").replace(".", "_").isidentifier()
    or "-" in k
    or "." in k[:-3]
}
if odd:
    for k, v in list(odd.items())[:5]:
        assigns = re.findall(r"^\s+(\S+) = BashOperator\($", v, re.M)
        check(
            f"{k}: python variable names are valid identifiers",
            all(a.isidentifier() for a in assigns),
            str(assigns[:2]),
        )
else:
    print("  (none in this project - nothing to check)")

failed = [r for r in results if not r[0]]
print(f"\n{'='*70}\nRESULT: {len(results)-len(failed)}/{len(results)} assertions passed")
if failed:
    print("FAILED:")
    for _, label, detail in failed:
        print(f"  - {label}  {detail}")
sys.exit(1 if failed else 0)
